"""Seeded / staged adapter (PRD S5.P0.2, S11, S21).

This adapter is the honest stand-in for two things this environment cannot get:

  * a live IMD block bulletin (the coarse forecast input), and
  * ERA5-Land / CHIRPS / IMD-gridded historical reference (the fine target).

Both are generated by a *documented, deterministic* function of date and
Panchayat terrain, seeded with `config.RANDOM_SEED`. Consequences, stated
plainly:

  * The generator is physically motivated (seasonal cycle + lapse + aspect +
    vegetation + a fixed per-Panchayat offset) so the downscaling pipeline has
    real structure to learn and real structure to miss.
  * Stageing the generator instead of a real reanalysis product means the
    validation metrics demonstrate PIPELINE CORRECTNESS, not real-world skill.
    Every response and screen carries that caveat.
  * Because it is deterministic, the same numbers appear on every machine, the
    demo never depends on the network, and the backtest is reproducible.

Replacing this adapter requires no change to the model, the API or the UI.
"""

from __future__ import annotations

import math
from datetime import date, timedelta
from typing import Dict, List, Optional

import numpy as np

from .. import config
from ..canonical import BlockForecast, ForecastDay, HindcastRecord, Panchayat
from ..provenance import SEEDED_FORECAST, STAGED_HINDCAST
from .base import AdapterResult, WeatherDataAdapter

# ---------------------------------------------------------------------------
# Generative constants. Kept explicit and reviewable — not tuned for a target
# accuracy number. The only purpose is a physically plausible seasonal cycle
# plus a terrain-driven local component.
# ---------------------------------------------------------------------------
BASE_TMAX_MEAN_C = 32.5
SEASONAL_AMP_C = 5.5
SEASONAL_PEAK_DOY = 120          # mid/late April — pre-monsoon peak
BLOCK_NOISE_SIGMA_C = 1.0
REFERENCE_NOISE_SIGMA_C = 0.85

# Terrain-driver magnitudes. In a real landscape the temperature anomaly of a
# Panchayat is dominated by elevation (the lapse term, fixed at 6.5 C/km by the
# PRD) and only secondarily by aspect and vegetation. These coefficients were
# set to that ordering: aspect contributes roughly a third of the lapse span
# over the practical slope range, and NDVI a modest amount on top. They are NOT
# tuned to produce a nicer skill score; if anything, a flatter aspect term makes
# the B2 lapse-rate baseline harder to beat.
ASPECT_COEF_C = 0.8
NDVI_COEF_C = 1.6
SPATIAL_COEF_C = 0.35

RAIN_SEASON_AMP_MM = 14.0
RAIN_SEASON_PEAK_DOY = 205       # late July
RAIN_FLOOR_MM = 0.0
RAIN_NOISE_SIGMA_MM = 1.2


def _doy(d: date) -> int:
    return d.timetuple().tm_yday


def seasonal_tmax_c(d: date) -> float:
    phase = 2.0 * math.pi * (_doy(d) - SEASONAL_PEAK_DOY) / 365.25
    return BASE_TMAX_MEAN_C + SEASONAL_AMP_C * math.cos(phase)


def seasonal_rainfall_mm(d: date) -> float:
    phase = 2.0 * math.pi * (_doy(d) - RAIN_SEASON_PEAK_DOY) / 365.25
    return max(RAIN_FLOOR_MM, RAIN_SEASON_AMP_MM * (0.5 + 0.5 * math.cos(phase)))


def _true_anomaly_c(p: Panchayat, z_bar: float, index: int, ndvi_bar: float) -> float:
    """The 'truth' the model tries to recover: a fixed terrain offset."""
    lapse = -config.LAPSE_RATE_C_PER_KM * (p.elevation_m - z_bar) / 1000.0
    aspect = ASPECT_COEF_C * math.cos(math.radians(p.aspect_deg)) * (p.slope_deg / 10.0)
    ndvi = -NDVI_COEF_C * (p.ndvi - ndvi_bar)
    spatial = SPATIAL_COEF_C * math.sin(index * 1.7)
    return lapse + aspect + ndvi + spatial


def _area_weighted_mean_elevation(panchayats: List[Panchayat]) -> float:
    total = sum(p.area_km2 for p in panchayats)
    return sum(p.area_km2 * p.elevation_m for p in panchayats) / total


def _ndvi_mean(panchayats: List[Panchayat]) -> float:
    return sum(p.ndvi for p in panchayats) / len(panchayats)


class SeededAdapter(WeatherDataAdapter):
    """Deterministic fixture provider (always available)."""

    name = "seeded"

    def available(self) -> bool:
        return True

    # -- coarse block forecast ------------------------------------------
    def block_forecast(self, block_id: str, dates: List[str]) -> AdapterResult:
        days: List[ForecastDay] = []
        for i, iso in enumerate(dates):
            d = date.fromisoformat(iso)
            rng = np.random.default_rng(
                config.RANDOM_SEED + d.toordinal() + abs(hash(block_id)) % 9973
            )
            t_max = seasonal_tmax_c(d) + float(rng.normal(0.0, BLOCK_NOISE_SIGMA_C))
            t_min = t_max - float(rng.uniform(9.0, 13.0))
            rain = max(
                RAIN_FLOOR_MM,
                seasonal_rainfall_mm(d) + float(rng.normal(0.0, RAIN_NOISE_SIGMA_MM)),
            )
            days.append(
                ForecastDay(
                    date=iso,
                    t_max_c=round(t_max, 1),
                    t_min_c=round(t_min, 1),
                    rainfall_mm=round(rain, 1),
                    lead_days=i + 1,
                )
            )
        return AdapterResult(
            ok=True,
            provenance=SEEDED_FORECAST,
            data=BlockForecast(block_id=block_id, days=days, provenance=SEEDED_FORECAST.as_dict()),
            detail="seeded block forecast generated deterministically",
        )

    # -- staged hindcast (Track A reference) -----------------------------
    def hindcast_pairs(self, block_id: str, panchayats: List[Panchayat]) -> AdapterResult:
        import json as _json

        staged = config.HINDCAST_FILE
        if staged.exists():
            with open(staged, "r", encoding="utf-8") as fh:
                payload = _json.load(fh)
            records = [
                HindcastRecord(
                    date=r["date"],
                    panchayat_id=r["panchayat_id"],
                    block_t_max_c=float(r["block_t_max_c"]),
                    reference_t_max_c=float(r["reference_t_max_c"]),
                    block_rainfall_mm=r.get("block_rainfall_mm"),
                    reference_rainfall_mm=r.get("reference_rainfall_mm"),
                )
                for r in payload["records"]
            ]
            return AdapterResult(
                ok=True,
                provenance=STAGED_HINDCAST,
                data=records,
                detail=payload.get("detail", "staged hindcast loaded from fixture"),
            )

        records = self._generate_hindcast(panchayats)
        return AdapterResult(
            ok=True,
            provenance=STAGED_HINDCAST,
            data=records,
            detail=(
                "generated deterministically (seed=%d) because no ERA5-Land/CHIRPS "
                "fixture is staged" % config.RANDOM_SEED
            ),
        )

    def _generate_hindcast(self, panchayats: List[Panchayat]) -> List[HindcastRecord]:
        z_bar = _area_weighted_mean_elevation(panchayats)
        ndvi_bar = _ndvi_mean(panchayats)
        anomalies = {
            p.panchayat_id: _true_anomaly_c(p, z_bar, i, ndvi_bar)
            for i, p in enumerate(panchayats)
        }

        start = date.fromisoformat("2015-01-01")
        end = date.fromisoformat("2024-12-31")
        n_days = (end - start).days + 1

        # Daily block signal — independent of Panchayat, as a real block
        # forecast would be.
        rng_block = np.random.default_rng(config.RANDOM_SEED)
        doys = np.array([_doy(start + timedelta(days=i)) for i in range(n_days)])
        seasonal = BASE_TMAX_MEAN_C + SEASONAL_AMP_C * np.cos(
            2.0 * np.pi * (doys - SEASONAL_PEAK_DOY) / 365.25
        )
        block_tmax = seasonal + rng_block.normal(0.0, BLOCK_NOISE_SIGMA_C, n_days)
        rain_seasonal = np.maximum(
            0.0,
            RAIN_SEASON_AMP_MM * (0.5 + 0.5 * np.cos(2.0 * np.pi * (doys - RAIN_SEASON_PEAK_DOY) / 365.25)),
        )
        block_rain = np.maximum(
            0.0, rain_seasonal + rng_block.normal(0.0, RAIN_NOISE_SIGMA_MM, n_days)
        )

        records: List[HindcastRecord] = []
        for p in panchayats:
            rng_p = np.random.default_rng(config.RANDOM_SEED + int(p.lgd_code))
            ref_tmax = block_tmax + anomalies[p.panchayat_id] + rng_p.normal(
                0.0, REFERENCE_NOISE_SIGMA_C, n_days
            )
            # P1 rainfall reference: block value modulated by a small,
            # Panchayat-specific multiplicative factor.
            factor = 1.0 + 0.35 * math.sin(anomalies[p.panchayat_id] * 1.3)
            ref_rain = np.maximum(0.0, block_rain * factor + rng_p.normal(0.0, 0.4, n_days))
            for i in range(n_days):
                records.append(
                    HindcastRecord(
                        date=(start + timedelta(days=i)).isoformat(),
                        panchayat_id=p.panchayat_id,
                        block_t_max_c=round(float(block_tmax[i]), 3),
                        reference_t_max_c=round(float(ref_tmax[i]), 3),
                        block_rainfall_mm=round(float(block_rain[i]), 3),
                        reference_rainfall_mm=round(float(ref_rain[i]), 3),
                    )
                )
        return records

    def station_observations(self, block_id: str, panchayats: List[Panchayat]) -> AdapterResult:
        return AdapterResult(
            ok=False,
            provenance=STAGED_HINDCAST,
            data=None,
            detail=config.DISCLAIMER_TRACK_B_ABSENT,
        )


def true_anomaly_c(p: Panchayat, panchayats: List[Panchayat]) -> float:
    """Exposed for tests only — the generator's ground truth for one Panchayat."""
    return _true_anomaly_c(
        p,
        _area_weighted_mean_elevation(panchayats),
        [q.panchayat_id for q in panchayats].index(p.panchayat_id),
        _ndvi_mean(panchayats),
    )


def demo_forecast_dates(n_days: int = 3, start: Optional[date] = None) -> List[str]:
    """Seeded demo dates.

    The default window is the pre-monsoon heat window (18-20 April), which is
    genuinely the hottest part of the year in the Nashik belt. Picking a
    seasonally honest window means the heat-risk advisory fires on the seeded
    forecast without anyone tuning a number to make the demo look better.
    """
    start = start or date(2026, 4, 18)
    return [(start + timedelta(days=i)).isoformat() for i in range(n_days)]
