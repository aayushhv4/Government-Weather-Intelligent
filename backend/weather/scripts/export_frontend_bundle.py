#!/usr/bin/env python
"""Export an offline snapshot for the dashboard (PRD S19, S7 fallbacks).

The judge demo must not depend on the network or on a running service. This
script captures the *exact* API responses for the pilot block and inlines them
into `frontend/LAST_GOV_API_GRAPHS_FINAL.html` between the markers

    /* KS_WEATHER_BUNDLE_START */   ...   /* KS_WEATHER_BUNDLE_END */

The dashboard prefers the live service and only uses this snapshot when the
service is unreachable — and it says so in a visible banner. The snapshot keeps
its true provenance (`source_type: simulated_demo`); a fallback never upgrades
provenance.

Run from `backend/weather`:

    python scripts/export_frontend_bundle.py
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

SERVICE_DIR = Path(__file__).resolve().parents[1]
if str(SERVICE_DIR) not in sys.path:
    sys.path.insert(0, str(SERVICE_DIR))

from ksweather import config  # noqa: E402
from ksweather.advisory import list_crops, load_rules  # noqa: E402
from ksweather.adapters import registry  # noqa: E402
from ksweather.pipeline import get_engine  # noqa: E402

DASHBOARD = SERVICE_DIR.parent.parent / "frontend" / "LAST_GOV_API_GRAPHS_FINAL.html"
BUNDLE_FILE = (
    SERVICE_DIR.parent.parent.parent
    / "website"
    / "data"
    / "weather-bundle.js"
)

START = "/* KS_WEATHER_BUNDLE_START */"
END = "/* KS_WEATHER_BUNDLE_END */"


def build_bundle(demo_days: int = 3) -> dict:
    engine = get_engine()
    engine.ensure_ready()
    block_id = engine.block_id

    forecast_adapter = registry.select_forecast_adapter()
    from ksweather.adapters.seeded import demo_forecast_dates

    dates = demo_forecast_dates(demo_days)
    fc = forecast_adapter.block_forecast(block_id, dates)
    days = [d.as_dict() for d in fc.data.days]
    prov = fc.provenance.as_dict()

    forecast = {
        "block_id": block_id,
        "source_type": prov["source_type"],
        "provenance": prov,
        "disclaimer": config.DISCLAIMER_DEMO_DATA,
        "days": days,
        "note": "Illustrative demo data — not an official IMD forecast.",
    }

    downscale = engine.downscale(
        block_id,
        [
            {
                "date": d["date"],
                "t_max_c": d["t_max_c"],
                "t_min_c": d.get("t_min_c"),
                "rainfall_mm": d.get("rainfall_mm"),
                "lead_days": d.get("lead_days", 1),
            }
            for d in days
        ],
    )

    rules = load_rules()
    return {
        "generated_note": (
            "Bundled snapshot of the live API responses. Simulated / staged data. "
            "Used only when the weather service is unreachable."
        ),
        "pilot": engine.pilot_payload(),
        "forecast": forecast,
        "downscale": downscale,
        "validation": engine.validation,
        "rainfall": {**(engine.rainfall_validation or {}), "p1": True},
        "provenance": engine.provenance_payload(),
        "rules": {
            "version": rules.get("version"),
            "disclaimer": rules.get("disclaimer"),
            "crops": list_crops(rules),
            "p0_variable": rules.get("p0_variable"),
            "p1_variable": rules.get("p1_variable"),
            "alert_prefix": rules.get("alert_prefix"),
            "default_risk_message": rules.get("default_risk_message"),
            "rainfall_rules": rules.get("rainfall_rules"),
            "raw": rules,
        },
    }


def render(bundle: dict) -> str:
    payload = json.dumps(bundle, ensure_ascii=False, separators=(",", ":"))
    return f"{START}\nwindow.KS_WEATHER_BUNDLE = {payload};\n{END}"


def splice(html: str, block: str) -> tuple[str, bool]:
    pattern = re.compile(re.escape(START) + r".*?" + re.escape(END), re.DOTALL)
    if not pattern.search(html):
        return html, False
    return pattern.sub(lambda _m: block, html, count=1), True


def main() -> int:
    bundle = build_bundle()
    block = render(bundle)

    BUNDLE_FILE.parent.mkdir(parents=True, exist_ok=True)
    BUNDLE_FILE.write_text(
        "/* Generated by backend/weather/scripts/export_frontend_bundle.py — do not edit by hand. */\n"
        + block + "\n",
        encoding="utf-8",
    )
    print(f"wrote {BUNDLE_FILE} ({len(block):,} bytes)")

    if not DASHBOARD.exists():
        print(f"dashboard not found at {DASHBOARD}; skipped inline splice")
        return 1
    html = DASHBOARD.read_text(encoding="utf-8")
    updated, ok = splice(html, block)
    if not ok:
        print("bundle markers not found in the dashboard — nothing spliced")
        return 1
    DASHBOARD.write_text(updated, encoding="utf-8")
    print(f"spliced bundle into {DASHBOARD.name} ({len(block):,} bytes inline)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
